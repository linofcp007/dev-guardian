/**
 * The class families the hunt grader keys on — eval-plan.md, "Classificação":
 * a hunt finding counts as finding a key entry when the file matches, the
 * line is within ±3 of a key line, AND its class is in the same family as
 * the key's. This table is the plan's `evals/classes.json`; `run.ts
 * --write-spec-sets` writes it there from here, so the two never drift.
 *
 * Families OVERLAP on purpose. They exist to absorb the honest ambiguity of
 * naming one bug — a BOLA is `broken-access-control` to one reader and
 * `business-logic` to another; a hard-coded JWT key is `secrets`,
 * `crypto-weakness` or `authentication` — not to make every class match
 * every other. Two classes are "in the same family" when at least one
 * family holds both ({@link sameFamily}). A class is always in its own
 * family.
 *
 * Typed against the closed list in `src/llmscan/classes.ts`, so a class that
 * is renamed or removed there is a compile error here, and the unit test
 * fails when a class is added there without a family.
 */

import { HUNT_CLASSES, type HuntClass } from '../../../src/llmscan/classes.js';

export const CLASS_FAMILIES: Readonly<Record<string, readonly HuntClass[]>> = {
  /** Untrusted data interpreted by a query, command or document language. */
  injection: [
    'sql-injection',
    'nosql-injection',
    'command-injection',
    'code-injection',
    'template-injection',
    'ldap-injection',
    'xpath-injection',
    'header-injection',
    'xxe',
  ],
  /** Ways the attacker ends up running code on the server. */
  'code-execution': ['code-injection', 'command-injection', 'deserialization', 'template-injection'],
  /** Output that reaches a browser unescaped, or sends it elsewhere. */
  'client-side': ['xss', 'template-injection', 'header-injection', 'open-redirect'],
  /** The server (or the victim's browser) sent to a target the attacker names. */
  'request-forgery': ['ssrf', 'open-redirect', 'csrf'],
  /** A file the attacker names is read or written. */
  'file-access': ['path-traversal', 'xxe'],
  /** Who may do what: object- and function-level authorization, bound fields, workflow abuse. */
  'access-control': ['broken-access-control', 'mass-assignment', 'authentication', 'csrf', 'business-logic'],
  /** Proving who someone is: tokens, keys, signatures and how they are made and checked. */
  authentication: ['authentication', 'secrets', 'crypto-weakness', 'misconfiguration'],
  /** Data handed to someone who should not have it — including "who exists" (enumeration). */
  'data-exposure': ['sensitive-data-exposure', 'secrets', 'misconfiguration', 'broken-access-control', 'authentication'],
  /** Exhausting the service, or abusing a flow's timing. */
  availability: ['dos', 'business-logic'],
};

const FAMILIES_OF: ReadonlyMap<string, ReadonlySet<string>> = (() => {
  const out = new Map<string, Set<string>>();
  for (const [family, members] of Object.entries(CLASS_FAMILIES)) {
    for (const c of members) {
      const set = out.get(c) ?? new Set<string>();
      set.add(family);
      out.set(c, set);
    }
  }
  return out;
})();

/** The families `cls` belongs to; empty for a string that is not a hunt class. */
export function familiesOf(cls: string): string[] {
  return [...(FAMILIES_OF.get(cls) ?? [])].sort();
}

/**
 * Whether `a` and `b` share a family. A class equals itself even when it is
 * in no family; a string outside the closed list matches nothing else (the
 * submission validator rejects it before grading ever sees it).
 */
export function sameFamily(a: string, b: string): boolean {
  if (a === b) return true;
  const fa = FAMILIES_OF.get(a);
  const fb = FAMILIES_OF.get(b);
  if (fa === undefined || fb === undefined) return false;
  for (const f of fa) if (fb.has(f)) return true;
  return false;
}

/** Classes of the closed list that no family holds — must be empty (unit-tested). */
export function classesWithoutFamily(): HuntClass[] {
  return HUNT_CLASSES.filter((c) => !FAMILIES_OF.has(c));
}

/** The `classes.json` document eval-plan.md names. */
export function classesDocument(): { note: string; classes: readonly string[]; families: Record<string, readonly string[]> } {
  return {
    note:
      'Generated by `npm run eval:llm-scan -- --write-spec-sets` from mcp/test/evals/llmScan/families.ts. ' +
      'Two classes are in the same family when at least one family holds both; a class always matches itself.',
    classes: [...HUNT_CLASSES],
    families: { ...CLASS_FAMILIES },
  };
}
