/**
 * Renders the two generated reference pages — `docs/tools.md` and
 * `docs/rule-packs.md` — from the things they describe: the registered MCP
 * surface and the Semgrep pack files. Pure: every input is passed in, so the
 * drift test (`docs.test.ts`) and the writer (`generateDocs.ts`, run by
 * `npm run build`) produce the same bytes from the same source.
 *
 * Why generated at all: every hand-maintained copy of these facts drifted.
 * The README said 57 tools while CLAUDE.md said 54 and `mcp/README.md` said
 * both; CLAUDE.md's pack table said 134 rules across nine packs after a tenth
 * pack had shipped. A page that is derived cannot say anything the registry
 * or the pack files do not.
 *
 * Lives under `test/` for the reason `test/ablate/` does: it is developer
 * tooling that must never reach `dist/`, and `tsconfig.test.json` already
 * type-checks this tree at full strictness. It is not a vitest test (the
 * collector only takes `*.test.ts`).
 */

