/**
 * The shell guard against the commands a developer or an assistant runs all
 * day. None of them may be denied: a guard that blocks ordinary work teaches
 * its user to switch it off, and then it guards nothing.
 *
 * Each rule the guard gains is a regex or a word-level model, and each one can
 * reach further than its author meant. The rules' own tests pin their near
 * misses; this corpus pins everything else — the git, npm, docker, find, sed
 * and curl-to-an-API commands that make up a session — so that a rule which
 * over-reaches fails here, by name, instead of in someone's terminal.
 *
 * A warning is allowed (`sudo`, `git reset --hard`, `rm -rf node_modules`
 * warn on purpose); a block is not. Add to it freely; never remove an entry
 * to make a rule pass.
 */

