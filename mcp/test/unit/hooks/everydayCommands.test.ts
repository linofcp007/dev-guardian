describe('the shell guard over an everyday corpus — no command is denied', () => {
  it('holds a corpus of a realistic size', () => {
    expect(BASH.length).toBeGreaterThanOrEqual(180);
    expect(POWERSHELL.length).toBeGreaterThanOrEqual(70);
  });

  /** The rules that denied it — none — so a failure names the command and the rule. */
  const denied = (command: string, shell: 'bash' | 'powershell'): { command: string; deniedBy: string[] } => {
    const a = assessBashCommand(command, { shell });
    return { command, deniedBy: a.level === 'block' ? a.rules : [] };
  };

  it.each(BASH)('Bash: %j is not denied', (command) => {
    expect(denied(command, 'bash')).toEqual({ command, deniedBy: [] });
  });

  it.each(POWERSHELL)('PowerShell: %j is not denied', (command) => {
    expect(denied(command, 'powershell')).toEqual({ command, deniedBy: [] });
  });
});
